# 3. 可读值：把数值变成人能一眼读懂的文本（只格式化，不重算）
# ---------------------------------------------------------------------------
# 单位为 "1"（比率）时默认转百分比；下列指标例外，按自身含义显示。
_RATIO_EXCEPT_PCT = {"floor_area_ratio_est"}
# 保持小数的比率指标（精度高于 1% 时百分比会丢信息）
_RATIO_KEEP_DECIMAL = {"classify_precision_vs_recon", "classify_recall_vs_recon"}


def readable_value(value, unit: str, mid: str = "") -> str:
    """把数值格式化成可读文本。None → 「—」（不留空、不写缺口表述）。"""
    if value is None:
        return "—"
    if isinstance(value, bool):
        return "是" if value else "否"
    if unit == "1":
        if mid in _RATIO_EXCEPT_PCT:
            return f"{float(value):.2f}"
        if mid in _RATIO_KEEP_DECIMAL:
            return f"{float(value) * 100:.1f}%"
        return f"{float(value) * 100:.1f}%"
    if unit in ("栋", "个", "条", "处", "块", "棵"):
        return f"{int(round(float(value))):,}"
    if unit == "m²":
        return f"{float(value):,.0f}"
    if unit == "m":
        return f"{float(value):.1f}"
    if unit == "°":
        return f"{float(value):.1f}°"
    if unit == "个/100m²":
        return f"{float(value):.2f} 个 / 百平方米"
    if isinstance(value, int):
        return f"{value:,}"
    return f"{float(value):.4g}"


def readable_value_with_unit(value, unit: str, mid: str = "") -> str:
    """带单位后缀的可读值（导览页用，单位跟在数字后面更好读）。"""
    text = readable_value(value, unit, mid)
    suffix = unit_cn(unit)
    if unit in ("1", "") or not suffix:
        return text
    if text.startswith("—"):
        return text
    return f"{text} {suffix}"


def readable_range(rng, unit: str, mid: str = "", annotated: bool = True) -> str:
    """区间文本。

    有敏感性区间时给 min–max；没有时：溯源版写明「单点值」及原因，
    成品版写「—」，并在正文统一说明一次（不逐行重复缺口说明）。
    """
    if not rng or len(rng) != 2 or rng[0] is None or rng[1] is None:
        return "单点值（未做参数敏感性计算）" if annotated else "—"
    return (f"{readable_value(rng[0], unit, mid)} – "
            f"{readable_value(rng[1], unit, mid)}")


def readable_range_with_unit(rng, unit: str, mid: str = "", annotated: bool = True) -> str:
    """区间文本（带单位后缀），用于文档里的表格。"""
    if not rng or len(rng) != 2 or rng[0] is None or rng[1] is None:
        return "单点值（未做参数敏感性计算）" if annotated else "—"
    suffix = unit_cn(unit)
    if not suffix:
        return readable_range(rng, unit, mid, annotated)
    return (f"{readable_value(rng[0], unit, mid)} – "
            f"{readable_value(rng[1], unit, mid)} {suffix}")


# ---------------------------------------------------------------------------
# 4. 局限要点：把长段局限压成前几条真正要命的，通用尾巴单独一句话
# ---------------------------------------------------------------------------
# 06 步会在每条指标后面挂一段「共性局限」（无真值 / LOD 混合 / 顶面近似 / 顶点丢弃），
# 对每条都重复一遍，占满版面却抓不住重点。这里把共性尾巴摘掉，另用一句话交代。
_GENERIC_LIMIT_MARKERS = ("真值状态：", "绝对精度未验证")
_COMMON_LIMIT_TAIL = ("真值状态：仅绿化/道路做过样例两轮校核且未达阈值（格级 IoU 0.391 / 0.447），"
                      "其余指标无实测真值；模型混有 7 档精细度；顶面判定为近似算法。"
                      "共性局限见《现状指标》表的边界说明。")


def key_limits(limits: str, keep: int = 2) -> str:
    """从原文局限里提取要点（去掉每条重复的共性尾巴）。"""
    if not limits:
        return ""
    text = str(limits)
    parts = [p for p in text.replace("；", "。").split("。") if p.strip()]
    kept = []
    for part in parts:
        if any(mark in part for mark in _GENERIC_LIMIT_MARKERS):
            break
        kept.append(part.strip())
    if not kept:
        return text[:120]
    out = "；".join(kept[:keep])
    if len(kept) > keep:
        out += "；……"
    return out + "。" + _COMMON_LIMIT_TAIL


